CREATE TABLE VENDEDOR_REPO (
 ID_VEND_REPO NUMBER GENERATED AS IDENTITY,
 TOTAL_VENDEDORES INTEGER NOT NULL,
 FILTRO VARCHAR2(100),
 CONSTRAINT VENDEDOR_REPO_PK PRIMARY KEY (ID_VEND_REPO)
);
CREATE TABLE CLIENTE (
 ID_CLIENTE NUMBER GENERATED AS IDENTITY,
 NOME VARCHAR2(100) NOT NULL,
 EMPRESA VARCHAR2(100) NOT NULL,
 DATA_NASCIMENTO DATE NOT NULL,
 CONSTRAINT CLIENTE_PK PRIMARY KEY (ID_CLIENTE),
 CONSTRAINT CLIENTE_NOME_EMPRESA_UK UNIQUE (NOME, EMPRESA)
);
CREATE TABLE REUNIAO_REPO (
 ID_REUN_REPO NUMBER GENERATED AS IDENTITY,
 ARQUIVO_JSON CLOB NOT NULL,
 TOTAL_REUNIOES INTEGER NOT NULL,
 CONSTRAINT REUNIAO_REPO_PK PRIMARY KEY (ID_REUN_REPO)
);
CREATE TABLE VENDEDOR (
 ID_VENDEDOR NUMBER GENERATED AS IDENTITY,
 NOME VARCHAR2(100) NOT NULL,
 CARGO VARCHAR2(50) NOT NULL,
 SETOR VARCHAR2(50) NOT NULL,
 TOTAL_REUNIOES INTEGER NOT NULL,
 VENDEDOR_REPO_ID_VEND_REPO NUMBER NOT NULL,
 CONSTRAINT VENDEDOR_PK PRIMARY KEY (ID_VENDEDOR),
 CONSTRAINT VENDEDOR_VENDEDOR_REPO_FK FOREIGN KEY (VENDEDOR_REPO_ID_VEND_REPO) REFERENCES VENDEDOR_REPO (ID_VEND_REPO),
 CONSTRAINT VENDEDOR_NOME_UK UNIQUE (NOME)
);
CREATE TABLE REUNIAO (
 ID_REUNIAO NUMBER GENERATED AS IDENTITY,
 TRANSCRICAO VARCHAR2(4000) NOT NULL,
 DATA DATE NOT NULL,
 STATUS VARCHAR2(25) NOT NULL,
 CLIENTE_ID_CLIENTE NUMBER NOT NULL,
 VENDEDOR_ID_VENDEDOR NUMBER NOT NULL,
 REUNIAO_REPO_ID_REUN_REPO NUMBER NOT NULL,
 CONSTRAINT REUNIAO_PK PRIMARY KEY (ID_REUNIAO),
 CONSTRAINT REUNIAO_CLIENTE_FK FOREIGN KEY (CLIENTE_ID_CLIENTE) REFERENCES CLIENTE (ID_CLIENTE),
 CONSTRAINT REUNIAO_VENDEDOR_FK FOREIGN KEY (VENDEDOR_ID_VENDEDOR) REFERENCES VENDEDOR (ID_VENDEDOR),
 CONSTRAINT REUNIAO_REUNIAO_REPO_FK FOREIGN KEY (REUNIAO_REPO_ID_REUN_REPO) REFERENCES REUNIAO_REPO (ID_REUN_REPO),
 CONSTRAINT REUNIAO_CLIENTE_DATA_UK UNIQUE (CLIENTE_ID_CLIENTE, DATA)
);
CREATE TABLE ANALISE_IA (
 ID_ANALISE NUMBER GENERATED AS IDENTITY,
 TIPO INTEGER NOT NULL,
 RESULTADO VARCHAR2(250) NOT NULL,
 MODELO_IA VARCHAR2(75) NOT NULL,
 DATAHORA_EXECUCAO DATE NOT NULL,
 TOKENS_UTILIZADOS INTEGER NOT NULL,
 REUNIAO_ID_REUNIAO NUMBER NOT NULL,
 CONSTRAINT ANALISE_IA_PK PRIMARY KEY (ID_ANALISE),
 CONSTRAINT ANALISE_IA_REUNIAO_FK FOREIGN KEY (REUNIAO_ID_REUNIAO) REFERENCES REUNIAO (ID_REUNIAO),
 CONSTRAINT ANALISE_IA_REUNIAO_TIPO_UK UNIQUE (REUNIAO_ID_REUNIAO, TIPO)
);
COMMENT ON TABLE VENDEDOR_REPO IS 'Repositorio de filtros e informacoes de vendedores';
COMMENT ON TABLE CLIENTE IS 'Clientes participantes das reunioes comerciais';
COMMENT ON TABLE REUNIAO_REPO IS 'Repositorio de arquivos relacionados as reunioes';
COMMENT ON TABLE VENDEDOR IS 'Vendedores responsaveis pelas reunioes comerciais';
COMMENT ON TABLE REUNIAO IS 'Reunioes comerciais realizadas ou agendadas';
COMMENT ON TABLE ANALISE_IA IS 'Resultados de analises de inteligencia artificial sobre reunioes';
