-- AUXILIAR OPCIONAL, nao substitui a carga recebida. Demonstracao repetivel em schema de teste.
-- Cria somente registros com prefixo DEMO S4. Nao produz resultados ficticios de IA.
DECLARE vr NUMBER; rr NUMBER; c NUMBER; v NUMBER; n NUMBER;
BEGIN
 SELECT MIN(ID_VEND_REPO) INTO vr FROM VENDEDOR_REPO WHERE FILTRO='DEMO S4';
 IF vr IS NULL THEN INSERT INTO VENDEDOR_REPO(TOTAL_VENDEDORES,FILTRO) VALUES(0,'DEMO S4') RETURNING ID_VEND_REPO INTO vr; END IF;
 SELECT MIN(R.REUNIAO_REPO_ID_REUN_REPO) INTO rr FROM REUNIAO R JOIN CLIENTE C ON C.ID_CLIENTE=R.CLIENTE_ID_CLIENTE WHERE C.NOME='DEMO S4 Cliente' AND C.EMPRESA='DEMO S4 Empresa';
 IF rr IS NULL THEN INSERT INTO REUNIAO_REPO(ARQUIVO_JSON,TOTAL_REUNIOES) VALUES('{"reunioes":[]}',0) RETURNING ID_REUN_REPO INTO rr; END IF;
 SELECT MIN(ID_CLIENTE) INTO c FROM CLIENTE WHERE NOME='DEMO S4 Cliente' AND EMPRESA='DEMO S4 Empresa';
 IF c IS NULL THEN INSERT INTO CLIENTE(NOME,EMPRESA,DATA_NASCIMENTO) VALUES('DEMO S4 Cliente','DEMO S4 Empresa',DATE '1990-01-01') RETURNING ID_CLIENTE INTO c; END IF;
 SELECT MIN(ID_VENDEDOR) INTO v FROM VENDEDOR WHERE NOME='DEMO S4 Vendedor';
 IF v IS NULL THEN INSERT INTO VENDEDOR(NOME,CARGO,SETOR,TOTAL_REUNIOES,VENDEDOR_REPO_ID_VEND_REPO) VALUES('DEMO S4 Vendedor','Consultor','Tecnologia',0,vr) RETURNING ID_VENDEDOR INTO v; END IF;
 SELECT COUNT(*) INTO n FROM REUNIAO WHERE CLIENTE_ID_CLIENTE=c AND DATA=TO_DATE('2026-09-01 10:00:00','YYYY-MM-DD HH24:MI:SS');
 IF n=0 THEN INSERT INTO REUNIAO(TRANSCRICAO,DATA,STATUS,CLIENTE_ID_CLIENTE,VENDEDOR_ID_VENDEDOR,REUNIAO_REPO_ID_REUN_REPO) VALUES('Cliente: gostei da proposta, vamos avancar.',TO_DATE('2026-09-01 10:00:00','YYYY-MM-DD HH24:MI:SS'),'AGENDADA',c,v,rr); END IF;
 COMMIT;
EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
END;
/
