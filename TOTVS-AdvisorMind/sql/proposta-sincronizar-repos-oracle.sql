UPDATE VENDEDOR_REPO VR SET TOTAL_VENDEDORES=(SELECT COUNT(*) FROM VENDEDOR V WHERE V.VENDEDOR_REPO_ID_VEND_REPO=VR.ID_VEND_REPO);
UPDATE REUNIAO_REPO RR SET TOTAL_REUNIOES=(SELECT COUNT(*) FROM REUNIAO R WHERE R.REUNIAO_REPO_ID_REUN_REPO=RR.ID_REUN_REPO),
 ARQUIVO_JSON=TO_CLOB('{"reunioes":') || COALESCE((SELECT JSON_ARRAYAGG(R.ID_REUNIAO ORDER BY R.ID_REUNIAO RETURNING CLOB) FROM REUNIAO R WHERE R.REUNIAO_REPO_ID_REUN_REPO=RR.ID_REUN_REPO),TO_CLOB('[]')) || TO_CLOB('}');
