-- Copia auxiliar das cinco consultas recebidas; nenhuma mudanca semantica.
-- CONSULTA 1: Expressao para calculo na projecao.
-- Aplica uma margem hipotetica de 10% sobre os tokens utilizados.
SELECT ID_ANALISE, MODELO_IA, TOKENS_UTILIZADOS, TOKENS_UTILIZADOS * 1.10 AS TOKENS_COM_MARGEM FROM ANALISE_IA;
-- CONSULTA 2: INNER JOIN entre CLIENTE e REUNIAO.
SELECT C.NOME AS CLIENTE, C.EMPRESA, R.ID_REUNIAO, R.DATA, R.STATUS
FROM CLIENTE C INNER JOIN REUNIAO R ON C.ID_CLIENTE = R.CLIENTE_ID_CLIENTE;
-- CONSULTA 3: INNER JOIN com funcao de grupo e GROUP BY.
SELECT V.NOME AS VENDEDOR, COUNT(R.ID_REUNIAO) AS QTD_REUNIOES
FROM VENDEDOR V INNER JOIN REUNIAO R ON V.ID_VENDEDOR = R.VENDEDOR_ID_VENDEDOR
GROUP BY V.ID_VENDEDOR, V.NOME ORDER BY QTD_REUNIOES DESC;
-- CONSULTA 4: LEFT OUTER JOIN com WHERE e ORDER BY.
SELECT V.NOME AS VENDEDOR, V.SETOR, R.ID_REUNIAO, R.STATUS, R.DATA
FROM VENDEDOR V LEFT OUTER JOIN REUNIAO R ON V.ID_VENDEDOR = R.VENDEDOR_ID_VENDEDOR
WHERE V.SETOR = 'Tecnologia' ORDER BY V.NOME ASC, R.DATA DESC;
-- CONSULTA 5: GROUP BY com HAVING.
SELECT SETOR, AVG(TOTAL_REUNIOES) AS MEDIA_REUNIOES FROM VENDEDOR
GROUP BY SETOR HAVING AVG(TOTAL_REUNIOES) >= 7 ORDER BY MEDIA_REUNIOES DESC;
